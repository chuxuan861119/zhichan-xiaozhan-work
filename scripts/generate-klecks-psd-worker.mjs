import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";

export async function generatePsdWorker(check = false) {
  const license = await readFile("vendor/klecks/node_modules/ag-psd/LICENSE", "utf8");
  const result = await build({
    entryPoints: ["vendor/klecks/src/app/script/klecks/storage/psd-codec-worker.ts"],
    bundle: true,
    write: false,
    platform: "browser",
    target: "chrome100",
    format: "iife",
    minify: true,
    legalComments: "eof",
    banner: { js: "/*! ag-psd 31.0.1 (MIT)\n" + license + "*/" },
  });
  const source =
    "// Generated by scripts/generate-klecks-psd-worker.mjs; do not edit.\n" +
    "// ag-psd and bundled transitive licenses are retained in the embedded source.\n" +
    "export const psdWorkerSource = " +
    JSON.stringify(result.outputFiles[0].text) +
    ";\n";
  const target = "vendor/klecks/src/app/script/klecks/storage/psd-codec-worker-source.ts";
  if (check) {
    if ((await readFile(target, "utf8")) !== source)
      throw new Error(
        "PSD worker bundle is stale; run node scripts/generate-klecks-psd-worker.mjs",
      );
  } else await writeFile(target, source);
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href)
  await generatePsdWorker(process.argv.includes("--check"));
